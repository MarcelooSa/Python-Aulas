# Leia dois números e mostre:
# A soma
# A subtração
# A multiplicação
# A divisão

print("Bem-vindo a máquina de operações!")
n1 = float(input("Digite o seu 1º número: "))
n2 = float(input("Digite o seu 2º número: "))
soma = n1 + n2
subtracao = n1 - n2
mult = n1 * n2
divisao = n1 / n2

print("O resultado da soma, subtração, multiplicação e divisão de", n1, "e", n2, "respectivamente é:", soma, ",", subtracao, ",", mult, "e", divisao, "!")
