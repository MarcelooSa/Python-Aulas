# Atividade 09 – Cálculo de Área
# Peça ao usuário a largura e a altura de um retângulo.
# Calcule e mostre a área total.

print("Cálculo de área do retângulo!")
largura = float(input("Informe a largura: "))
h = float(input("Informe a altura: "))
areaR = largura * h
print(f"A área de um retângulo com largura {largura} e altura {h} é {areaR:.2f}")