# Atividade 9 – Média de Notas
# Leia três notas de um aluno.
# Calcule e mostre a média final.

print("Bem-vindo ao sistema de cálculos de notas!")
n1 = float(input("Digite a sua 1ª nota: "))
n2 = float(input("Digite a sua 2ª nota: "))
n3 = float(input("Digite a sua 3ª nota: "))
media = (n1+n2+n3) / 3
print(f"A sua média final é {media:.2f}")