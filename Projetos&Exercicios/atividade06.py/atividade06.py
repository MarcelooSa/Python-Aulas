# Peça ao usuário para digitar dois números.
# Converta para int e mostre a soma dos dois valores.

print("Bem-vindo(a) a calculadora de somas!")
n1 = int(input("Digite o seu 1º número: "))
n2 = int(input("Digite o seu 2º número: "))
soma = n1 + n2
print(f"A soma de {n1} e {n2} é igual a {soma}.")